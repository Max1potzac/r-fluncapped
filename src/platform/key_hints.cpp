std::string hint_text(const std::string& key) {
    std::string k;
    for (char ch : key) k += ch == '_' ? ' ' : static_cast<char>(std::toupper(static_cast<unsigned char>(ch)));
    static const std::pair<const char*, std::string> kShort[] = {
        {"UP", {kUp}}, {"DOWN", {kDown}}, {"LEFT", {kLeft}}, {"RIGHT", {kRight}},
        {"SPACE", "SPC"}, {"RETURN", "ENT"}, {"BACKSPACE", "BKSP"}, {"DELETE", "DEL"}, {"INSERT", "INS"},
        {"PAGEUP", "PGUP"}, {"PAGEDOWN", "PGDN"}, {"CAPSLOCK", "CAPS"},
        {"LEFT SHIFT", "LSHF"}, {"RIGHT SHIFT", "RSHF"}, {"LEFT CTRL", "LCTL"}, {"RIGHT CTRL", "RCTL"},
        {"LEFT ALT", "LALT"}, {"RIGHT ALT", "RALT"},
    };
    for (const auto& [name, text] : kShort)
        if (k == name) return text;
    if (k.starts_with("KEYPAD ")) k = "KP" + k.substr(7);
    std::string out;
    for (char ch : k)
        if (ch != ' ' && glyph(ch)) out += ch;
    if (out.size() > 4) out.resize(4);
    return out;
}

std::vector<HintFill> layout_hint(const HintLabel& label, int surface_width, int surface_height) {
    std::vector<HintFill> fills;
    if (label.text.empty()) return fills;
    // A font pixel: 2 surface pixels at 720, 3 at 1080, 4 at 1440.
    int s = std::max(1, (surface_height + 180) / 360);
    int n = static_cast<int>(label.text.size());
    int w = 6 * s + n * 5 * s + (n - 1) * s, h = 7 * s + 6 * s;
    int x = label.anchor == HintLabel::Anchor::TopLeft ? label.x : label.x - w;
    int y = label.anchor == HintLabel::Anchor::TopLeft ? label.y : label.y - h;
    // A button at the surface's edge still gets its whole badge.
    x = std::clamp(x, 0, std::max(surface_width - w, 0));
    y = std::clamp(y, 0, std::max(surface_height - h, 0));
    fills.push_back({x, y, w, h, kHintBorder});
    fills.push_back({x + s, y + s, w - 2 * s, h - 2 * s, kHintBack});
    for (int i = 0; i < n; ++i) {
        const Glyph* g = glyph(label.text[i]);
        if (!g) continue;
        int gx = x + 3 * s + i * 6 * s, gy = y + 3 * s;
        for (int row = 0; row < 7; ++row) {
            // Each run of lit pixels in the row is one rectangle.
            for (int col = 0; col < 5;) {
                if (!(g->rows[row] & (0x10 >> col))) {
                    ++col;
                    continue;
                }
                int start = col;
                while (col < 5 && (g->rows[row] & (0x10 >> col))) ++col;
                fills.push_back({gx + start * s, gy + row * s, (col - start) * s, s, label.text_rgb});
            }
        }
    }
    return fills;
}

std::vector<HintFill> layout_box(const HintBox& box, int surface_height) {
    std::vector<HintFill> fills;
    if (box.w <= 0 || box.h <= 0) return fills;
    int t = std::max(3, (surface_height + 180) / 240);  // the line: 3 pixels at 720, 5 at 1080
    int x = box.x, y = box.y, w = box.w, h = box.h;
    // A dark edge first, a pixel wider all round, so the line shows on light tiles too.
    for (auto [rgb, grow] : {std::pair{kHintBack, 1}, std::pair{box.rgb, 0}}) {
        int lx = x - grow, ly = y - grow, lw = w + 2 * grow, lh = h + 2 * grow, lt = t + 2 * grow;
        fills.push_back({lx, ly, lw, lt, rgb});
        fills.push_back({lx, ly + lh - lt, lw, lt, rgb});
        fills.push_back({lx, ly, lt, lh, rgb});
        fills.push_back({lx + lw - lt, ly, lt, lh, rgb});
    }
    return fills;
}

