# Regenerates src/platform/cursor_sprites.inc from assets/cursor.png, a sheet of two glove
# sprites: the cursor (left) and the cursor while clicking (right). Run from the repo's root:
#   python3 tools/gen_cursor.py
# Needs Pillow. Each sprite is cropped to what's drawn and stored as PNG bytes.
from PIL import Image
import io

sheet = Image.open("assets/cursor.png").convert("RGBA")
w, h = sheet.size
alpha = sheet.split()[3]
# The sprites are split by the columns left empty between them.
cols = [x for x in range(w) if any(alpha.getpixel((x, y)) for y in range(h))]
parts, start = [], cols[0]
for a, b in zip(cols, cols[1:] + [None]):
    if b is None or b != a + 1:
        parts.append((start, a + 1))
        if b is not None:
            start = b
assert len(parts) == 2, parts
out = ["// Generated by tools/gen_cursor.py from assets/cursor.png; don't edit.\n"]
for name, (x0, x1) in zip(["kCursorPng", "kCursorDownPng"], parts):
    sprite = sheet.crop((x0, 0, x1, h))
    sprite = sprite.crop(sprite.getbbox())
    buf = io.BytesIO()
    sprite.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    out.append(f"static const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 20):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",\n")
    out.append("};\n")
open("src/platform/cursor_sprites.inc", "w").write("".join(out))
